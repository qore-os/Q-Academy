const dictionaries = { de, en, it, es, fr } satisfies Record<AppLocale, Dictionary>;
const courseBuilderActionCodeSet = new Set<string>(courseBuilderActionCodes);

export function getCourseBuilderActionMessage(
  locale: AppLocale,
  code: CourseBuilderServerActionCode,
) {
  if (courseBuilderActionCodeSet.has(code)) {
    return dictionaries[locale][code as CourseBuilderActionCode];
  }
  return getCourseContentCopyCopy(locale).action[code as CourseContentCopyActionCode];
}
