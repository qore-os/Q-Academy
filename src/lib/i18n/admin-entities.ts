const dictionaries = { de, en, it, es, fr } satisfies Record<
  AppLocale,
  AdminEntityDictionary
>;

export type AdminEntityCopy = (
  key: AdminEntityUiKey,
  values?: Readonly<Record<string, string | number>>,
) => string;

export function getAdminEntityCopy(locale: AppLocale): AdminEntityCopy {
  const dictionary = dictionaries[locale];
  return (key, values) =>
    dictionary[key].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (token, name) =>
      values && name in values ? String(values[name]) : token,
    );
}

export function formatAdminEntityNumber(value: number, locale: AppLocale) {
  return new Intl.NumberFormat(intlLocale(locale)).format(value);
}

export function formatAdminEntityDifficulty(
  value: string,
  copy: AdminEntityCopy,
) {
  if (value === "beginner" || value === "Grundlagen") {
    return copy("common.difficulty.beginner");
  }
  if (value === "intermediate" || value === "Fortgeschritten") {
    return copy("common.difficulty.intermediate");
  }
  if (value === "advanced" || value === "Experte") {
    return copy("common.difficulty.advanced");
  }
  return value;
}

